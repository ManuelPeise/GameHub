using System.Reflection;
using System.Text;
using System.Text.Json;

namespace Tests.Shared;

/// <summary>
/// Generates TypeScript types from the DTOs in Shared.Models: records become types, enums become string
/// unions (the API serializes enums as names), static classes with string constants become const objects.
/// </summary>
internal static class TypeScriptContractGenerator
{
    private static readonly NullabilityInfoContext Nullability = new();

    public static string Generate(Assembly assembly, IReadOnlyList<string> namespaces)
    {
        ArgumentNullException.ThrowIfNull(assembly);

        var types = assembly.GetExportedTypes()
            .Where(type => type.Namespace is not null && namespaces.Contains(type.Namespace))
            .OrderBy(type => namespaces.ToList().IndexOf(type.Namespace!))
            .ThenBy(type => type.IsEnum ? 0 : IsConstantsClass(type) ? 1 : 2)
            .ThenBy(type => type.Name, StringComparer.Ordinal)
            .ToList();

        var output = new StringBuilder();
        output.Append("// <auto-generated>\n");
        output.Append("// Generated from Shared.Models by Tests.Shared/TypeScriptContractGenerator.cs. Do not edit.\n");
        output.Append("// Regenerate: set GAMEHUB_UPDATE_CONTRACTS=1 and run dotnet test (Tests.Shared).\n");
        output.Append("// </auto-generated>\n");

        foreach (var type in types)
        {
            output.Append('\n');
            if (type.IsEnum)
            {
                var names = Enum.GetNames(type).Select(name => $"\"{name}\"");
                output.Append($"export type {type.Name} = {string.Join(" | ", names)};\n");
            }
            else if (IsConstantsClass(type))
            {
                output.Append($"export const {type.Name} = {{\n");
                foreach (var field in ConstantFields(type))
                {
                    output.Append($"  {field.Name}: {JsonSerializer.Serialize(field.GetRawConstantValue())},\n");
                }

                output.Append("} as const;\n");
            }
            else if (type.IsClass && !type.IsAbstract)
            {
                output.Append($"export type {type.Name} = {{\n");
                foreach (var property in type.GetProperties(BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly)
                             .OrderBy(property => property.MetadataToken))
                {
                    var info = Nullability.Create(property);
                    var nullable = info.ReadState == NullabilityState.Nullable
                                   || Nullable.GetUnderlyingType(property.PropertyType) is not null;
                    var name = JsonNamingPolicy.CamelCase.ConvertName(property.Name);
                    var tsType = MapType(property.PropertyType, info);
                    output.Append(nullable ? $"  {name}?: {tsType} | null;\n" : $"  {name}: {tsType};\n");
                }

                output.Append("};\n");
            }
        }

        return output.ToString();
    }

    private static bool IsConstantsClass(Type type) =>
        type is { IsAbstract: true, IsSealed: true } && ConstantFields(type).Any();

    private static IEnumerable<FieldInfo> ConstantFields(Type type) =>
        type.GetFields(BindingFlags.Public | BindingFlags.Static)
            .Where(field => field.IsLiteral && field.FieldType == typeof(string))
            .OrderBy(field => field.MetadataToken);

    private static string MapType(Type type, NullabilityInfo info)
    {
        var underlying = Nullable.GetUnderlyingType(type) ?? type;

        if (underlying == typeof(string) || underlying == typeof(Guid) || underlying == typeof(DateTimeOffset)
            || underlying == typeof(DateTime) || underlying == typeof(TimeSpan) || underlying == typeof(DateOnly)
            || underlying == typeof(TimeOnly))
        {
            return "string";
        }

        if (underlying == typeof(bool))
        {
            return "boolean";
        }

        if (underlying == typeof(int) || underlying == typeof(long) || underlying == typeof(short) || underlying == typeof(byte)
            || underlying == typeof(double) || underlying == typeof(float) || underlying == typeof(decimal))
        {
            return "number";
        }

        if (underlying.IsEnum)
        {
            return underlying.Name;
        }

        if (underlying.IsArray && info.ElementType is { } elementInfo)
        {
            return $"{MapType(underlying.GetElementType()!, elementInfo)}[]";
        }

        if (underlying.IsGenericType)
        {
            var definition = underlying.GetGenericTypeDefinition();
            var arguments = underlying.GetGenericArguments();
            if (definition == typeof(Dictionary<,>) || definition == typeof(IReadOnlyDictionary<,>) || definition == typeof(IDictionary<,>))
            {
                return $"Record<string, {MapType(arguments[1], info.GenericTypeArguments[1])}>";
            }

            if (typeof(System.Collections.IEnumerable).IsAssignableFrom(underlying))
            {
                return $"{MapType(arguments[0], info.GenericTypeArguments[0])}[]";
            }
        }

        return underlying.Name;
    }
}
